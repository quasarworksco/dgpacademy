  const NS = 'http://www.w3.org/2000/svg';
  const sprite = document.createElementNS(NS, 'svg');
  sprite.setAttribute('width', '0'); sprite.setAttribute('height', '0'); sprite.setAttribute('aria-hidden', 'true');
  sprite.style.position = 'absolute';
  sprite.innerHTML = Object.keys(P).map(k => '<symbol id="ic-' + k + '" viewBox="0 0 24 24">' + P[k] + '</symbol>').join('');
  const style = document.createElement('style');
  style.textContent = '.ic{width:1em;height:1em;display:inline-block;vertical-align:-.14em;flex:none;fill:none;stroke:currentColor;stroke-width:1.9;stroke-linecap:round;stroke-linejoin:round;overflow:visible}' +
    '.ic .ic-fill,.ic-fill{fill:currentColor;stroke:none}';
  const mount = () => { document.body.insertBefore(sprite, document.body.firstChild); document.head.appendChild(style); };
  if (document.body) mount(); else document.addEventListener('DOMContentLoaded', mount);

  window.icon = function (name, cls, color) {
    return '<svg class="ic' + (cls ? ' ' + cls : '') + '"' + (color ? ' style="color:' + color + '"' : '') + ' aria-hidden="true"><use href="#ic-' + name + '"/></svg>';
  };
  // Icono para un emoji (o null si no hay equivalente)
  window.emojiIcon = function (e, cls) {
    const k = String(e || '').replace(/️/g, '');
    const m = MAP[k] || MAP[[...k][0]];
    return m ? window.icon(m[0], cls, m[1]) : null;
  };

  // ── Reemplazo automático de emojis en el contenido ──
  const RE = /(?:\p{Extended_Pictographic}️?(?:‍\p{Extended_Pictographic}️?)*|✦)/gu;
  const SKIP = 'script, style, pre, code, textarea, input, [contenteditable], .no-ic, [class*="code"], [class^="c-"]';
  const tpl = document.createElement('template');
  function fixText(node) {
    const txt = node.nodeValue;
    RE.lastIndex = 0;
    if (!RE.test(txt)) return;
    const el = node.parentElement;
    if (!el || el.closest(SKIP)) return;
    if (el.closest('svg')) { node.nodeValue = txt.replace(RE, '').replace(/^\s+/, ''); return; }   // texto de diagramas
    RE.lastIndex = 0;
    const html = txt.replace(/[&<>]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]))
      .replace(RE, m => window.emojiIcon(m) || '');
    tpl.innerHTML = html;
    el.replaceChild(tpl.content, node);
  }
  function scan(root) {
    if (!root) return;
    if (root.nodeType === 3) { fixText(root); return; }
    if (root.nodeType !== 1 || root.closest && root.closest('script, style')) return;
    RE.lastIndex = 0;
    if (!RE.test(root.textContent || '')) return;
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const list = []; let n;
    while ((n = w.nextNode())) list.push(n);
    list.forEach(fixText);
  }
  window.scanIcons = scan;
  const start = () => {
    scan(document.body);
    new MutationObserver(muts => muts.forEach(m => {
      if (m.type === 'characterData') fixText(m.target);
      else m.addedNodes.forEach(scan);
    })).observe(document.body, { subtree: true, childList: true, characterData: true });
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
